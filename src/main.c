#include "stm32f1xx.h"

/* =========================================================
 * Мигание светодиодом на PC13
 * =========================================================
 * На Blue Pill встроенный светодиод подключён к PC13,
 * активный уровень — низкий (PC13=0 → светодиод горит).
 * ========================================================= */

int main(void)
{
    /* 1. Включить тактирование GPIOC */
    RCC->APB2ENR |= RCC_APB2ENR_IOPCEN;

    /* 2. Настроить PC13 как выход push-pull, 2 MHz */
    GPIOC->CRH &= ~(GPIO_CRH_MODE13 | GPIO_CRH_CNF13);
    GPIOC->CRH |= (0x2UL << GPIO_CRH_MODE13_Pos);

    /* 3. Мигаем */
    while (1)
    {
        GPIOC->ODR ^= GPIO_ODR_ODR13;

        /* Простая задержка на пустом цикле.
         * Позже заменим на SysTick — точный миллисекундный таймер. */
        for (volatile uint32_t i = 0; i < 500000; i++)
        {
        }
    }
}